"""
ReportGenerator — SRP: only generates text reports. No analysis. No actions.
Implements IReporter (DIP).
"""

from typing import Any
from src.core.interfaces import IReporter
from src.analysis.risk_scorer import RiskProfile, RiskLevel


class ReportGenerator(IReporter):
    """
    Generates Markdown burnout reports from analysis results.
    SRP: only knows how to format reports.
    """

    def get_format(self) -> str:
        return "markdown"

    def generate(self, analysis_results: dict[str, Any]) -> str:
        summary = analysis_results.get("summary", {})
        high_risk: list[RiskProfile] = analysis_results.get("high_risk", [])
        medium_risk: list[RiskProfile] = analysis_results.get("medium_risk", [])

        lines = [
            "# 🔥 Engineering Team Health Report",
            f"_Generated by Talent Intelligence Agent · Powered by Coral_\n",
            "---",
            "## 📊 Team Summary\n",
            f"| Metric | Value |",
            f"|--------|-------|",
            f"| Total Engineers | {summary.get('total_engineers', 0)} |",
            f"| 🔴 High Risk | {summary.get('high_risk_count', 0)} |",
            f"| 🟠 Medium Risk | {summary.get('medium_risk_count', 0)} |",
            f"| 🟢 Low Risk | {summary.get('low_risk_count', 0)} |",
            f"| Avg Risk Score | {summary.get('avg_risk_score', 0)}/100 |",
            f"| Most At Risk | **{summary.get('most_at_risk', 'N/A')}** |",
            f"| Top Signal | {summary.get('top_signal', 'N/A')} |",
            "",
        ]

        if high_risk:
            lines += [
                "---",
                "## 🔴 High Risk Engineers — Immediate Action Required\n",
            ]
            for p in high_risk:
                lines += self._format_profile(p)

        if medium_risk:
            lines += [
                "---",
                "## 🟠 Medium Risk Engineers — Monitor Closely\n",
            ]
            for p in medium_risk:
                lines += self._format_profile(p)

        lines += [
            "---",
            "## ℹ️ Data Sources Used (via Coral)",
            "- **GitHub** — commit timestamps, after-hours activity",
            "- **Slack** — message frequency, sentiment, response latency",
            "- **Google Calendar** — meeting hours, declined events",
            "",
            "_All data queried 100% locally via Coral. No data left your machine._",
        ]

        return "\n".join(lines)

    # ── Private ───────────────────────────────────────────────────────────────

    def _format_profile(self, p: RiskProfile) -> list[str]:
        emoji = "🔴" if p.risk_level == RiskLevel.HIGH else "🟠"
        signals = " | ".join(
            f"{k}: {v:.0f}pts"
            for k, v in sorted(p.signal_breakdown.items(), key=lambda x: -x[1])
            if v > 0
        )
        return [
            f"### {emoji} {p.engineer_name} — Score: {p.burnout_risk_score}/100",
            f"**Team:** {p.team} | **Manager:** {p.manager_email}",
            f"**Dominant Signal:** {p.dominant_signal}",
            f"**Signal Breakdown:** {signals}",
            f"**Raw Signals:**",
            f"- Late night commits: {p.raw_data.get('late_night_commits', 0)}",
            f"- Weekly meeting hours: {p.raw_data.get('weekly_meeting_hours', 0):.1f}h",
            f"- Slack complaints: {p.raw_data.get('slack_complaints', 0)}",
            "",
        ]
